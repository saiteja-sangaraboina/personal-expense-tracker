/**
 * cacheHeaders.js - HTTP response security and dynamic API cache control headers
 */

const setSecurityAndCacheHeaders = (req, res, next) => {
  // Security headers
  res.setHeader('X-Content-Type-Options', 'nosniff');
  res.setHeader('X-Frame-Options', 'DENY');
  res.setHeader('X-XSS-Protection', '1; mode=block');

  // Dynamic API endpoints should never be cached by intermediaries
  if (req.path && req.path.startsWith('/api')) {
    res.setHeader('Cache-Control', 'no-store, no-cache, must-revalidate, proxy-revalidate');
    res.setHeader('Pragma', 'no-cache');
    res.setHeader('Expires', '0');
  }

  next();
};

module.exports = setSecurityAndCacheHeaders;
